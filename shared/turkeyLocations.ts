/**
 * Kullanıcı girdisini il ve ilçe veritabanında arar.
 * "kadıköy", "ankara", "izmir konak", "çankaya", "bursa nilüfer" vb. destekler.
 */
export function searchTurkishLocations(query: string, limit = 8): LocationSearchResult[] {
  const norm = normalizeTurkishText(query);
  if (!norm || norm.length < 2) return [];

  const results: LocationSearchResult[] = [];
  const seen = new Set<string>();

  // 1. İl isimlerinde tam veya başlangıç eşleşmesi
  for (const prov of TURKISH_PROVINCES) {
    const pNorm = normalizeTurkishText(prov.name);
    if (pNorm.startsWith(norm) || pNorm === norm) {
      const key = prov.name;
      if (!seen.has(key)) {
        seen.add(key);
        results.push({ label: prov.name, province: prov.name, lat: prov.lat, lon: prov.lon });
      }
    }
  }

  // 2. İlçe ve "İlçe, İl" araması
  for (const prov of TURKISH_PROVINCES) {
    const pNorm = normalizeTurkishText(prov.name);
    for (const dist of prov.districts) {
      const dNorm = normalizeTurkishText(dist);
      const combo1 = `${dNorm} ${pNorm}`;
      const combo2 = `${pNorm} ${dNorm}`;
      if (
        dNorm.startsWith(norm) ||
        dNorm === norm ||
        combo1.includes(norm) ||
        combo2.includes(norm)
      ) {
        const key = `${dist}, ${prov.name}`;
        if (!seen.has(key)) {
          seen.add(key);
          const coordKey = `${dNorm}-${pNorm}`;
          const known = KNOWN_DISTRICT_COORDS[coordKey];
          const coords = known || { lat: prov.lat, lon: prov.lon };
          results.push({
            label: key,
            province: prov.name,
            district: dist,
            lat: coords.lat,
            lon: coords.lon,
            ...(known ? {} : { approximate: true }),
          });
          if (results.length >= limit) return results;
        }
      }
    }
  }

  // 3. İl isimlerinde içerir (contains) eşleşmesi
  if (results.length < limit) {
    for (const prov of TURKISH_PROVINCES) {
      const pNorm = normalizeTurkishText(prov.name);
      if (pNorm.includes(norm) && !seen.has(prov.name)) {
        seen.add(prov.name);
        results.push({ label: prov.name, province: prov.name, lat: prov.lat, lon: prov.lon });
        if (results.length >= limit) return results;
      }
    }
  }

  return results;
}

/**
 * Metin sorgusunu (örn. "Kadıköy", "Kadıköy, İstanbul", "İzmir") doğrudan koordinata çözer.
 */
export function resolveTurkishLocation(query: string): { latitude: number; longitude: number; label: string; province: string; district?: string; approximate: boolean } | null {
  const matches = searchTurkishLocations(query, 1);
  if (matches[0]) {
    return {
      latitude: matches[0].lat,
      longitude: matches[0].lon,
      label: matches[0].label,
      province: matches[0].province,
      district: matches[0].district,
      approximate: Boolean(matches[0].approximate),
    };
  }
  return null;
}

/**
 * Verilen GPS koordinatlarına Türkiye sınırları içinde en yakın ili bulur.
 */
export function findClosestProvince(lat: number, lon: number): TurkishProvince {
  let closest = TURKISH_PROVINCES[0];
  let minDistance = Infinity;

  for (const prov of TURKISH_PROVINCES) {
    const d = (prov.lat - lat) ** 2 + (prov.lon - lon) ** 2;
    if (d < minDistance) {
      minDistance = d;
      closest = prov;
    }
  }

  return closest;
}
